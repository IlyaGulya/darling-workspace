"""Exercise roster generation, drift detection and instruction-file isolation."""
from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "scripts" / "dwdiag-roster.py"
BEGIN = "<!-- dwdiag-roster:begin (generated by scripts/dwdiag-roster.py; do not edit by hand) -->"
END = "<!-- dwdiag-roster:end -->"


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="dwdiag-roster-contract-") as directory:
        root = Path(directory)
        (root / "scripts").mkdir()
        (root / "docs").mkdir()
        generator = root / "scripts" / GENERATOR.name
        shutil.copy2(GENERATOR, generator)
        tool = root / "scripts" / "dwdiag"
        tool.write_text(
            "#!/bin/sh\n"
            "if [ \"$1\" = --help ]; then\n"
            "  printf 'Commands:\\n  inspect  Inspect an artifact\\n  help  Print help\\n'\n"
            "else\n"
            "  printf 'Inspect an artifact | report its identity\\n\\nUsage: dwdiag inspect\\n'\n"
            "fi\n"
        )
        tool.chmod(0o755)
        docs = root / "docs" / "tooling.md"
        docs.write_text(f"Before reference\n{BEGIN}\nstale\n{END}\nAfter reference\n")
        instructions = root / "AGENTS.md"
        instructions.write_bytes(b"Read the diagnostic skill before measuring.\n")
        original = instructions.read_bytes()

        def run(flag: str) -> subprocess.CompletedProcess[str]:
            return subprocess.run(
                [sys.executable, "-B", str(generator), flag],
                capture_output=True, text=True, cwd=root,
            )

        stale = run("--check")
        assert stale.returncode == 1, stale.stdout + stale.stderr
        written = run("--write")
        assert written.returncode == 0, written.stdout + written.stderr
        assert instructions.read_bytes() == original, "generator rewrote task instructions"
        current = run("--check")
        assert current.returncode == 0, current.stdout + current.stderr
        # Discovery must not require an instruction file in the first place.
        instructions.unlink()
        absent = run("--check")
        assert absent.returncode == 0, absent.stdout + absent.stderr
        tool.write_text(tool.read_text().replace("  inspect  Inspect", "  changed  Inspect"))
        changed = run("--check")
        assert changed.returncode == 1, changed.stdout + changed.stderr
        docs.write_text("No generated reference markers\n")
        missing = run("--check")
        assert missing.returncode == 2, missing.stdout + missing.stderr
        assert docs.read_text() == "No generated reference markers\n"
    print("PASS dwdiag-roster-contract")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
