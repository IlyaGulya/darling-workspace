#!/usr/bin/env python3
"""Generate the diagnostic command reference from the tool's own help.

    scripts/dwdiag-roster.py --write
    scripts/dwdiag-roster.py --check

The roster belongs in docs/tooling.md. Task instructions route agents there
instead of repeating a generated command list in their always-loaded context.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DWDIAG = ROOT / "scripts" / "dwdiag"
DOCS = ROOT / "docs" / "tooling.md"

BEGIN = "<!-- dwdiag-roster:begin (generated by scripts/dwdiag-roster.py; do not edit by hand) -->"
END = "<!-- dwdiag-roster:end -->"


def run(args: list[str]) -> str:
    proc = subprocess.run([str(DWDIAG), *args], capture_output=True, text=True)
    return proc.stdout + proc.stderr


def command_names() -> list[str]:
    text = run(["--help"])
    names: list[str] = []
    in_commands = False
    for line in text.splitlines():
        if line.strip().startswith("Commands:"):
            in_commands = True
            continue
        if in_commands:
            m = re.match(r"^  ([a-z][a-z0-9-]*)\b", line)
            if m and m.group(1) != "help":
                names.append(m.group(1))
            elif line.strip() and not line.startswith(" "):
                break
    return names


def command_description(name: str) -> str:
    text = run([name, "--help"])
    for line in text.splitlines():
        if not line.strip() or line.startswith("dwdiag:"):
            continue
        if line.startswith("Usage:"):
            continue
        return line.strip().replace("|", "\\|")
    return ""


def build_block() -> str:
    names = command_names()
    rows = [f"| `dwdiag {name}` | {command_description(name)} |" for name in names]
    table = ["| command | what it answers |", "|---|---|", *rows]
    return "\n".join(table)


def replace_block(text: str, begin: str, end: str, body: str) -> str:
    start = text.find(begin)
    if start == -1:
        raise SystemExit(f"marker not found: {begin}")
    stop = text.find(end, start)
    if stop == -1:
        raise SystemExit(f"marker not found: {end}")
    return text[: start + len(begin)] + "\n" + body + "\n" + text[stop:]


def up_to_date() -> tuple[bool, str]:
    docs = DOCS.read_text()
    try:
        new_docs = replace_block(docs, BEGIN, END, build_block())
    except SystemExit as exc:
        return False, str(exc)
    return new_docs == docs, ""


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="rewrite the marked blocks in place")
    group.add_argument("--check", action="store_true", help="fail when a marked block is stale")
    args = parser.parse_args(argv)

    if args.write:
        DOCS.write_text(replace_block(DOCS.read_text(), BEGIN, END, build_block()))
        print(f"dwdiag roster: wrote {len(command_names())} commands into docs/tooling.md")
        return 0

    ok, problem = up_to_date()
    if problem:
        print(f"dwdiag roster: {problem}", file=sys.stderr)
        return 2
    if not ok:
        print(
            "dwdiag roster is STALE: the tool has commands the documents do not list.\n"
            "Run scripts/dwdiag-roster.py --write and commit the result.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
